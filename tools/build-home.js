/* Builds the home page in three languages from tools/home-template.html:
     index.html     Italian  (https://migame.es/)
     es/index.html  Spanish  (https://migame.es/es/)
     en/index.html  English  (https://migame.es/en/)

   Edit the template (texts are in the T dictionary inside it), then run:
     node tools/build-home.js
   and upload the three files. Never edit the three generated files by hand. */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const tpl = fs.readFileSync(path.join(__dirname, "home-template.html"), "utf8");

/* read the T dictionary out of the page script */
const tStart = tpl.indexOf("var T = {");
const tEnd = tpl.indexOf("\n  };", tStart) + 5;
const T = new Function(tpl.slice(tStart, tEnd) + " return T;")();

const PAGES = {
  it: {
    file: "index.html", r: "", url: "https://migame.es/", locale: "it_IT",
    desc: "Lezioni individuali online di programmazione per bambini e principianti: dai blocchi di Scratch al codice vero, fino al primo videogioco. In italiano, spagnolo e inglese.",
    imgAlt: "mi.Game: dai blocchi di Scratch al codice vero"
  },
  es: {
    file: "es/index.html", r: "../", url: "https://migame.es/es/", locale: "es_ES",
    desc: "Clases individuales online de programación para niños y principiantes: de los bloques de Scratch al código de verdad, hasta su primer videojuego. En español, italiano e inglés.",
    imgAlt: "mi.Game: de los bloques de Scratch al código de verdad"
  },
  en: {
    file: "en/index.html", r: "../", url: "https://migame.es/en/", locale: "en_GB",
    desc: "One-to-one online coding lessons for kids and beginners: from Scratch blocks to real code, all the way to their first video game. In English, Italian and Spanish.",
    imgAlt: "mi.Game: from Scratch blocks to real code"
  }
};
const LOCALES = { it: "it_IT", es: "es_ES", en: "en_GB" };

const attr = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const plain = (s) => String(s).replace(/<[^>]+>/g, "");

for (const [lang, p] of Object.entries(PAGES)) {
  const d = T[lang];
  let html = tpl
    .split("{{GENERATED}}").join("GENERATED by tools/build-home.js from tools/home-template.html. Do not edit by hand.")
    .split("{{LANG}}").join(lang)
    .split("{{TITLE}}").join(attr(d.pageTitle))
    .split("{{DESC}}").join(attr(p.desc))
    .split("{{URL}}").join(p.url)
    .split("{{IMGALT}}").join(attr(p.imgAlt))
    .split("{{LOCALE}}").join(p.locale)
    .split("{{LOCALE_ALT}}").join(Object.keys(LOCALES).filter((l) => l !== lang)
      .map((l) => '  <meta property="og:locale:alternate" content="' + LOCALES[l] + '">').join("\n"))
    .split("{{R}}").join(p.r);

  /* write the texts straight into the page, so search engines read them even without running the script */
  html = html.replace(/(<(\w+)\b[^>]*\sdata-t="(\w+)"[^>]*>)(<\/\2>)/g, (m, open, tag, key, close) =>
    d[key] === undefined ? m : open + d[key] + close);
  html = html.replace(/(\salt="")(\s[^>]*data-t-alt="(\w+)")/g, (m, a, rest, key) =>
    d[key] === undefined ? m : ' alt="' + attr(plain(d[key])) + '"' + rest);

  const out = path.join(ROOT, p.file);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, html);
  const left = (html.match(/\{\{\w+\}\}/g) || []);
  console.log(p.file, left.length ? "UNFILLED " + left.join(",") : "ok");
}
